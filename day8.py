#break statement
for x in "rama":
    if x == "m":
        break
    else:
        print(x)
        
        
#pass statement
for x in "rama":
    if x == "m":
        pass
    else:
        print(x)        
        
        
#continue statement        
for x in "rama":
    if x == "m":
        continue
    else:
        print(x)  
        
